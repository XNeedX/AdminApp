#!/usr/bin/env node
/**
 * TEMPORARY OpenAPI augmentation bridge (specs/006-appointment-management, task T002).
 *
 * The live Appointments API Swagger documents every action as an untyped `IActionResult`
 * (no response schema), exposes enums as bare integers, and omits the read models that
 * the endpoints actually return. That makes a typed client impossible to generate.
 *
 * This script downloads the live definition, adds the missing response schemas that match
 * the backend DTOs (read-only inspection of AppointmentsAPI), names the enum values, and
 * rewrites the `/api/*` paths to the Gateway shape
 * (`/appointments/{everything}` -> downstream `/api/{everything}`).
 *
 * It produces a spec overlay only. No HTTP client is written by hand: the client is still
 * generated by ng-openapi-gen. Delete this script and the overlay once the backend
 * publishes `[ProducesResponseType]` and enum names.
 *
 * Usage: node scripts/augment-appointments-openapi.mjs [sourceUrlOrFile]
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const DEFAULT_SOURCE = 'http://localhost:5203/swagger/v1/swagger.json';
const OUTPUT_PATH = resolve('openapi/appointments.openapi.json');

/** Shared `{ isSuccess, message, errors, data }` envelope of every Appointments API response. */
function envelopeSchema(dataSchema) {
  return {
    type: 'object',
    properties: {
      isSuccess: { type: 'boolean' },
      message: { type: 'string', nullable: true },
      errors: { type: 'array', items: { type: 'string' } },
      ...(dataSchema === null ? {} : { data: dataSchema }),
    },
    additionalProperties: false,
  };
}

/** Id that the backend returns from a 201 create. */
const GUID_SCHEMA = { type: 'string', format: 'uuid' };

/** JSON response body helper. */
function jsonBody(schemaRef) {
  return {
    description: 'Success',
    content: {
      'application/json': { schema: { $ref: schemaRef } },
    },
  };
}

function failureResponses() {
  return {
    400: jsonBody('#/components/schemas/ApiResponse'),
    403: jsonBody('#/components/schemas/ApiResponse'),
    404: jsonBody('#/components/schemas/ApiResponse'),
    409: jsonBody('#/components/schemas/ApiResponse'),
  };
}

async function loadDefinition(source) {
  if (/^https?:\/\//i.test(source)) {
    let response;
    try {
      response = await fetch(source);
    } catch (error) {
      throw new Error(
        `Cannot reach ${source}. Start the Appointments API (or pass a local swagger.json path).\n${error.message}`
      );
    }

    if (!response.ok) {
      throw new Error(`${source} responded with HTTP ${response.status}.`);
    }

    return response.json();
  }

  return JSON.parse(await readFile(resolve(source), 'utf8'));
}

function ensureSchemas(definition) {
  const schemas = definition.components?.schemas;
  if (schemas === undefined) {
    throw new Error('The definition has no components.schemas section.');
  }

  // Enum labels so the generated client keeps the business vocabulary.
  schemas.Status ??= {
    type: 'integer',
    format: 'int32',
    enum: [0, 1],
  };
  schemas.ServiceCategory ??= {
    type: 'integer',
    format: 'int32',
    enum: [0, 1, 2],
  };

  // Read models returned by `/Doctors`, `/Offices`, `/Services`, `/Specializations`.
  schemas.Doctor ??= {
    type: 'object',
    properties: {
      id: { type: 'string', format: 'uuid' },
      firstName: { type: 'string' },
      lastName: { type: 'string' },
      middleName: { type: 'string', nullable: true },
      specialization: { type: 'string' },
      status: { $ref: '#/components/schemas/Status' },
    },
    additionalProperties: false,
  };

  schemas.Office ??= {
    type: 'object',
    properties: {
      id: { type: 'string', format: 'uuid' },
      status: { $ref: '#/components/schemas/Status' },
      address: { type: 'string' },
    },
    additionalProperties: false,
  };

  schemas.Service ??= {
    type: 'object',
    properties: {
      id: { type: 'string', format: 'uuid' },
      name: { type: 'string' },
      status: { $ref: '#/components/schemas/Status' },
      category: { $ref: '#/components/schemas/ServiceCategory' },
    },
    additionalProperties: false,
  };

  schemas.Specialization ??= {
    type: 'object',
    properties: {
      id: { type: 'string', format: 'uuid' },
      name: { type: 'string' },
      status: { $ref: '#/components/schemas/Status' },
    },
    additionalProperties: false,
  };

  // List read model.
  schemas.ViewAppointmentListDTO ??= {
    type: 'object',
    properties: {
      id: { type: 'string', format: 'uuid' },
      startTime: { type: 'string', format: 'date-time' },
      endTime: { type: 'string', format: 'date-time' },
      doctorFullName: { type: 'string' },
      patientFullName: { type: 'string' },
      patientPhoneNumber: { type: 'string' },
      serviceName: { type: 'string' },
      isApproved: { type: 'boolean' },
    },
    additionalProperties: false,
  };

  schemas.ApiResponse = envelopeSchema(null);
  schemas.ApiResponseOfGuid = envelopeSchema(GUID_SCHEMA);
  schemas.ApiResponseOfIEnumerableOfString = envelopeSchema({
    type: 'array',
    items: { type: 'string' },
  });
  schemas.ApiResponseOfIEnumerableOfViewAppointmentListDTO = envelopeSchema({
    type: 'array',
    items: { $ref: '#/components/schemas/ViewAppointmentListDTO' },
  });
  schemas.ApiResponseOfIEnumerableOfDoctor = envelopeSchema({
    type: 'array',
    items: { $ref: '#/components/schemas/Doctor' },
  });
  schemas.ApiResponseOfIEnumerableOfOffice = envelopeSchema({
    type: 'array',
    items: { $ref: '#/components/schemas/Office' },
  });
  schemas.ApiResponseOfIEnumerableOfService = envelopeSchema({
    type: 'array',
    items: { $ref: '#/components/schemas/Service' },
  });
  schemas.ApiResponseOfIEnumerableOfSpecialization = envelopeSchema({
    type: 'array',
    items: { $ref: '#/components/schemas/Specialization' },
  });

  const enumNames = {
    Status: ['Active', 'Inactive'],
    ServiceCategory: ['Analyses', 'Consultations', 'Diagnostics'],
  };

  for (const [name, names] of Object.entries(enumNames)) {
    const schema = schemas[name];
    if (schema !== undefined && Array.isArray(schema.enum)) {
      schema['x-enumNames'] = names;
    }
  }
}

function rewriteResponses(definition) {
  const paths = definition.paths ?? {};

  const createPath = paths['/api/Appointments/{patientId}'];
  if (createPath?.post !== undefined) {
    createPath.post.responses = {
      200: jsonBody('#/components/schemas/ApiResponse'),
      ...failureResponses(),
    };
  }

  const approvePath = paths['/api/Appointments/{id}/approve'];
  if (approvePath?.patch !== undefined) {
    approvePath.patch.responses = {
      200: jsonBody('#/components/schemas/ApiResponse'),
      ...failureResponses(),
    };
  }

  const deletePath = paths['/api/Appointments/{id}'];
  if (deletePath?.delete !== undefined) {
    deletePath.delete.responses = {
      200: jsonBody('#/components/schemas/ApiResponse'),
      ...failureResponses(),
    };
  }

  const listPath = paths['/api/Appointments/receptionist'];
  if (listPath?.get !== undefined) {
    listPath.get.responses = {
      200: jsonBody('#/components/schemas/ApiResponseOfIEnumerableOfViewAppointmentListDTO'),
      ...failureResponses(),
    };
  }

  const slotsPath = paths['/api/Schedule/available-time-slots'];
  if (slotsPath?.get !== undefined) {
    slotsPath.get.responses = {
      200: jsonBody('#/components/schemas/ApiResponseOfIEnumerableOfString'),
      ...failureResponses(),
    };
  }

  const catalogResponses = [
    ['/api/Doctors', 'ApiResponseOfIEnumerableOfDoctor'],
    ['/api/Offices', 'ApiResponseOfIEnumerableOfOffice'],
    ['/api/Services', 'ApiResponseOfIEnumerableOfService'],
    ['/api/Specializations', 'ApiResponseOfIEnumerableOfSpecialization'],
  ];

  for (const [path, schema] of catalogResponses) {
    const item = paths[path];
    if (item?.get !== undefined) {
      item.get.responses = {
        200: jsonBody(`#/components/schemas/${schema}`),
        ...failureResponses(),
      };
    }
  }

  // Query parameter names are PascalCase in the backend DTO; normalize them so the
  // generated params interface is idiomatic. ASP.NET Core model binding is
  // case-insensitive, so the wire contract is unchanged.
  const paramRenames = {
    Date: 'date',
    DoctorName: 'doctorName',
    ServiceName: 'serviceName',
    IsApproved: 'isApproved',
    OfficeId: 'officeId',
    StartDate: 'startDate',
    EndDate: 'endDate',
    Page: 'page',
    PageSize: 'pageSize',
  };

  for (const item of Object.values(paths)) {
    for (const operation of Object.values(item)) {
      if (operation === null || typeof operation !== 'object' || !Array.isArray(operation.parameters)) {
        continue;
      }

      for (const parameter of operation.parameters) {
        const renamed = paramRenames[parameter.name];
        if (typeof renamed === 'string' && parameter.in === 'query') {
          parameter.name = renamed;
        }
      }
    }
  }
}

/**
 * The Gateway exposes `/appointments/{everything}` and forwards to `/api/{everything}`.
 * The generated client is configured with `rootUrl = ${environment.apiUrl}/appointments`,
 * so the `/api` prefix must be stripped from the operation paths.
 */
function rewritePathsForGateway(definition) {
  const rewritten = {};

  for (const [path, item] of Object.entries(definition.paths ?? {})) {
    const gatewayPath = path.startsWith('/api/') ? path.slice('/api'.length) : path;
    rewritten[gatewayPath] = item;
  }

  definition.paths = rewritten;
}

async function main() {
  const source = process.argv[2] ?? DEFAULT_SOURCE;
  const definition = await loadDefinition(source);

  ensureSchemas(definition);
  rewriteResponses(definition);
  rewritePathsForGateway(definition);

  definition.info = {
    ...definition.info,
    description: `${definition.info?.description ?? ''}\n\nTEMPORARY AdminApp overlay generated by scripts/augment-appointments-openapi.mjs (task T002).`.trim(),
  };

  await mkdir(dirname(OUTPUT_PATH), { recursive: true });
  await writeFile(OUTPUT_PATH, `${JSON.stringify(definition, null, 2)}\n`, 'utf8');

  console.log(`Augmented Appointments API definition written to ${OUTPUT_PATH}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
