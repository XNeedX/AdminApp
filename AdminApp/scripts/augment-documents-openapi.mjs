#!/usr/bin/env node
/**
 * TEMPORARY OpenAPI augmentation bridge (specs/009-receptionist-management, task T003).
 *
 * The live Documents API Swagger documents its actions as untyped `IActionResult`
 * (no response schema), so the upload id and the delete acknowledgment cannot be
 * generated. This overlay adds the response schemas that match the backend DTOs,
 * drops the PDF-specific endpoints that this application does not use, and rewrites
 * the `/api/*` paths to the Gateway shape (`/documents/{everything}` ->
 * downstream `/api/{everything}`).
 *
 * It produces a spec overlay only. No HTTP client is written by hand: the client is
 * still generated by ng-openapi-gen. Delete this script and the overlay once the
 * backend publishes `[ProducesResponseType]`.
 *
 * Usage: node scripts/augment-documents-openapi.mjs [sourceUrlOrFile]
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const DEFAULT_SOURCE = 'http://localhost:5105/swagger/v1/swagger.json';
const OUTPUT_PATH = resolve('openapi/documents.openapi.json');

function envelopeSchema(dataSchema) {
  return {
    type: 'object',
    properties: {
      isSuccess: { type: 'boolean' },
      message: { type: 'string', nullable: true },
      errors: { type: 'array', items: { type: 'string' } },
      ...(dataSchema === null ? {} : { data: dataSchema }),
    },
    additionalProperties: false,
  };
}

function jsonBody(schemaRef) {
  return {
    description: 'Success',
    content: {
      'application/json': { schema: { $ref: schemaRef } },
    },
  };
}

function failureResponses() {
  return {
    400: jsonBody('#/components/schemas/ApiResponse'),
    404: jsonBody('#/components/schemas/ApiResponse'),
    500: jsonBody('#/components/schemas/ApiResponse'),
  };
}

async function loadDefinition(source) {
  if (/^https?:\/\//i.test(source)) {
    let response;
    try {
      response = await fetch(source);
    } catch (error) {
      throw new Error(
        `Cannot reach ${source}. Start the Documents API (or pass a local swagger.json path).\n${error.message}`
      );
    }

    if (!response.ok) {
      throw new Error(`${source} responded with HTTP ${response.status}.`);
    }

    return response.json();
  }

  return JSON.parse(await readFile(resolve(source), 'utf8'));
}

function ensureSchemas(definition) {
  definition.components ??= {};
  definition.components.schemas ??= {};
  const schemas = definition.components.schemas;

  schemas.ApiResponse = envelopeSchema(null);
  schemas.ApiResponseOfGuid = envelopeSchema({ type: 'string', format: 'uuid' });
}

function rewriteResponses(definition) {
  const paths = definition.paths ?? {};

  const collectionPath = paths['/api/Documents'];
  if (collectionPath?.post !== undefined) {
    collectionPath.post.responses = {
      200: jsonBody('#/components/schemas/ApiResponseOfGuid'),
      ...failureResponses(),
    };
  }

  const byIdPath = paths['/api/Documents/{id}'];
  if (byIdPath?.delete !== undefined) {
    byIdPath.delete.responses = {
      200: jsonBody('#/components/schemas/ApiResponse'),
      ...failureResponses(),
    };
  }
}

/** Keep only the endpoints used by AdminApp (single file upload, read, delete). */
function keepRequiredPaths(definition) {
  const paths = definition.paths ?? {};

  for (const path of Object.keys(paths)) {
    if (path !== '/api/Documents' && path !== '/api/Documents/{id}') {
      delete paths[path];
    }
  }
}

function rewritePathsForGateway(definition) {
  const rewritten = {};

  for (const [path, item] of Object.entries(definition.paths ?? {})) {
    const gatewayPath = path.startsWith('/api/') ? path.slice('/api'.length) : path;
    rewritten[gatewayPath] = item;
  }

  definition.paths = rewritten;
}

async function main() {
  const source = process.argv[2] ?? DEFAULT_SOURCE;
  const definition = await loadDefinition(source);

  ensureSchemas(definition);
  rewriteResponses(definition);
  keepRequiredPaths(definition);
  rewritePathsForGateway(definition);

  definition.info = {
    ...definition.info,
    description: `${definition.info?.description ?? ''}\n\nTEMPORARY AdminApp overlay generated by scripts/augment-documents-openapi.mjs (task T003).`.trim(),
  };

  await mkdir(dirname(OUTPUT_PATH), { recursive: true });
  await writeFile(OUTPUT_PATH, `${JSON.stringify(definition, null, 2)}\n`, 'utf8');

  console.log(`Augmented Documents API definition written to ${OUTPUT_PATH}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
