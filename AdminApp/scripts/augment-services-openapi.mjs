#!/usr/bin/env node
/**
 * TEMPORARY OpenAPI augmentation bridge (specs/005-clinic-services-management, task T002).
 *
 * The live Services API Swagger (gap G1/G2/G3 in contracts/services-api.contract.md)
 * documents the Service actions as `IActionResult` without response schemas, reports
 * `200` for a `201` create, and exposes enums as bare integers. That makes a typed
 * client impossible to generate.
 *
 * This script downloads the live definition, adds the missing response schemas that
 * match the backend DTOs (read-only inspection of Services.Presentation), names the
 * enum values, and rewrites the `/api/*` paths to the Gateway shape
 * (`/services/{everything}` -> downstream `/api/{everything}`).
 *
 * It produces a spec overlay only. No HTTP client is written by hand: the client is
 * still generated by ng-openapi-gen. Delete this script and the overlay once the
 * backend publishes `[ProducesResponseType]` and enum names (task T037).
 *
 * Usage: node scripts/augment-services-openapi.mjs [sourceUrlOrFile]
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const DEFAULT_SOURCE = 'http://localhost:5095/swagger/v1/swagger.json';
const OUTPUT_PATH = resolve('openapi/services.openapi.json');

/** Shared `{ isSuccess, message, errors, data }` envelope of every Services API response. */
function envelopeSchema(dataSchema) {
  return {
    type: 'object',
    properties: {
      isSuccess: { type: 'boolean' },
      message: { type: 'string', nullable: true },
      errors: { type: 'array', items: { type: 'string' } },
      ...(dataSchema === null ? {} : { data: dataSchema }),
    },
    additionalProperties: false,
  };
}

/** `{ isSuccess, message, errors }` failure envelope. */
const FAILURE_ENVELOPE = { $ref: '#/components/schemas/ApiResponse' };

/** JSON response body helper. */
function jsonBody(schemaRef) {
  return {
    description: 'Success',
    content: {
      'application/json': { schema: { $ref: schemaRef } },
    },
  };
}

function noContent() {
  return { description: 'No Content' };
}

function failureResponses() {
  return {
    400: jsonBody('#/components/schemas/ApiResponse'),
    404: jsonBody('#/components/schemas/ApiResponse'),
  };
}

async function loadDefinition(source) {
  if (/^https?:\/\//i.test(source)) {
    let response;
    try {
      response = await fetch(source);
    } catch (error) {
      throw new Error(
        `Cannot reach ${source}. Start the Services API (or pass a local swagger.json path).\n${error.message}`
      );
    }

    if (!response.ok) {
      throw new Error(`${source} responded with HTTP ${response.status}.`);
    }

    return response.json();
  }

  return JSON.parse(await readFile(resolve(source), 'utf8'));
}

function ensureSchemas(definition) {
  const schemas = definition.components?.schemas;
  if (schemas === undefined) {
    throw new Error('The definition has no components.schemas section.');
  }

  // The response DTO is never referenced by the untyped actions, so it is absent today.
  schemas.ViewServiceDTO ??= {
    type: 'object',
    properties: {
      id: { type: 'string', format: 'uuid' },
      name: { type: 'string' },
      price: { type: 'number', format: 'double' },
      category: { $ref: '#/components/schemas/Category' },
      status: { $ref: '#/components/schemas/Status' },
      specializationId: { type: 'string', format: 'uuid' },
    },
    additionalProperties: false,
  };

  schemas.ApiResponse = envelopeSchema(null);
  schemas.ApiResponseOfViewServiceDTO = envelopeSchema({
    $ref: '#/components/schemas/ViewServiceDTO',
  });
  schemas.ApiResponseOfGuid = envelopeSchema({ type: 'string', format: 'uuid' });

  // Specialization read models (used by the Services tab to list a specialization's services).
  schemas.ViewSpecializationListDTO ??= {
    type: 'object',
    properties: {
      id: { type: 'string', format: 'uuid' },
      name: { type: 'string' },
      status: { $ref: '#/components/schemas/Status' },
    },
    additionalProperties: false,
  };

  schemas.PagedResultOfViewSpecializationListDTO ??= {
    type: 'object',
    properties: {
      items: {
        type: 'array',
        items: { $ref: '#/components/schemas/ViewSpecializationListDTO' },
      },
      totalCount: { type: 'integer', format: 'int32' },
    },
    additionalProperties: false,
  };

  schemas.ViewSpecializationServiceDTO ??= {
    type: 'object',
    properties: {
      id: { type: 'string', format: 'uuid' },
      name: { type: 'string' },
      price: { type: 'number', format: 'double' },
      status: { $ref: '#/components/schemas/Status' },
      category: { $ref: '#/components/schemas/Category' },
    },
    additionalProperties: false,
  };

  schemas.ViewSpecializationDTO ??= {
    type: 'object',
    properties: {
      id: { type: 'string', format: 'uuid' },
      status: { $ref: '#/components/schemas/Status' },
      name: { type: 'string' },
      services: {
        type: 'array',
        items: { $ref: '#/components/schemas/ViewSpecializationServiceDTO' },
      },
    },
    additionalProperties: false,
  };

  schemas.ApiResponseOfPagedResultOfViewSpecializationListDTO = envelopeSchema({
    $ref: '#/components/schemas/PagedResultOfViewSpecializationListDTO',
  });
  schemas.ApiResponseOfViewSpecializationDTO = envelopeSchema({
    $ref: '#/components/schemas/ViewSpecializationDTO',
  });

  // Preserve business labels through generation (gap G2).
  const enumNames = {
    Category: ['Analyses', 'Consultations', 'Diagnostics'],
    Status: ['Active', 'Inactive'],
  };

  for (const [name, names] of Object.entries(enumNames)) {
    const schema = schemas[name];
    if (schema !== undefined && Array.isArray(schema.enum)) {
      schema['x-enumNames'] = names;
    }
  }
}

/**
 * Resolves a path whether the definition still carries the `/api` prefix (fresh swagger)
 * or has already been rewritten for the Gateway (re-running this overlay on its own output).
 */
function findPath(paths, apiPath) {
  return paths[apiPath] ?? paths[apiPath.replace(/^\/api/, '')];
}

function rewriteResponses(definition) {
  const paths = definition.paths ?? {};
  const servicePath = findPath(paths, '/api/Service');
  const serviceByIdPath = findPath(paths, '/api/Service/{id}');
  const serviceStatusPath = findPath(paths, '/api/Service/{id}/status');

  if (servicePath?.post !== undefined) {
    servicePath.post.responses = {
      201: jsonBody('#/components/schemas/ApiResponseOfGuid'),
      ...failureResponses(),
    };
  }

  if (serviceByIdPath?.get !== undefined) {
    serviceByIdPath.get.responses = {
      200: jsonBody('#/components/schemas/ApiResponseOfViewServiceDTO'),
      ...failureResponses(),
    };
  }

  if (serviceByIdPath?.put !== undefined) {
    serviceByIdPath.put.responses = {
      204: noContent(),
      ...failureResponses(),
    };
  }

  if (serviceStatusPath?.patch !== undefined) {
    serviceStatusPath.patch.responses = {
      204: noContent(),
      ...failureResponses(),
    };
  }

  const specializationPath = findPath(paths, '/api/Specialization');
  const specializationByIdPath = findPath(paths, '/api/Specialization/{id}');
  const specializationStatusPath = findPath(paths, '/api/Specialization/{id}/status');

  if (specializationPath?.get !== undefined) {
    specializationPath.get.responses = {
      200: jsonBody('#/components/schemas/ApiResponseOfPagedResultOfViewSpecializationListDTO'),
      ...failureResponses(),
    };
  }

  if (specializationByIdPath?.get !== undefined) {
    specializationByIdPath.get.responses = {
      200: jsonBody('#/components/schemas/ApiResponseOfViewSpecializationDTO'),
      ...failureResponses(),
    };
  }

  // The untyped actions hide their success schemas, so the typed client cannot expose the
  // created id or the 204 acknowledgements. These match ApiController.HandleCreatedResult
  // and NoContent() in Services.Presentation (read-only backend inspection).
  if (specializationPath?.post !== undefined) {
    specializationPath.post.responses = {
      201: jsonBody('#/components/schemas/ApiResponseOfGuid'),
      ...failureResponses(),
    };
  }

  if (specializationByIdPath?.put !== undefined) {
    specializationByIdPath.put.responses = {
      204: noContent(),
      ...failureResponses(),
    };
  }

  if (specializationStatusPath?.patch !== undefined) {
    specializationStatusPath.patch.responses = {
      204: noContent(),
      ...failureResponses(),
    };
  }
}

/**
 * The Gateway exposes `/services/{everything}` and forwards to `/api/{everything}`.
 * The generated client is configured with `rootUrl = ${environment.apiUrl}/services`,
 * so the `/api` prefix must be stripped from the operation paths.
 */
function rewritePathsForGateway(definition) {
  const rewritten = {};

  for (const [path, item] of Object.entries(definition.paths ?? {})) {
    const gatewayPath = path.startsWith('/api/') ? path.slice('/api'.length) : path;
    rewritten[gatewayPath] = item;
  }

  definition.paths = rewritten;
}

async function main() {
  const source = process.argv[2] ?? DEFAULT_SOURCE;
  const definition = await loadDefinition(source);

  ensureSchemas(definition);
  rewriteResponses(definition);
  rewritePathsForGateway(definition);

  definition.info = {
    ...definition.info,
    description: `${definition.info?.description ?? ''}\n\nTEMPORARY AdminApp overlay generated by scripts/augment-services-openapi.mjs (task T002, removed by T037).`.trim(),
  };

  await mkdir(dirname(OUTPUT_PATH), { recursive: true });
  await writeFile(OUTPUT_PATH, `${JSON.stringify(definition, null, 2)}\n`, 'utf8');

  console.log(`Augmented Services API definition written to ${OUTPUT_PATH}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
